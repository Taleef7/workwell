/**
 * Build-time CQL → ELM compiler for the WorkWell measures (#106). Pure Node via
 * @cqframework/cql (Kotlin-Multiplatform, NO JVM) — the Path C build step, now
 * Java-free. Emits committed ELM JSON consumed by the runtime engine
 * (src/engine/cql/CqlExecutionEngine).
 *
 *   pnpm compile-measures [measures-src-dir] [out-elm-dir]
 *
 * Runs under `node --import tsx` because it shares the UCUM validator with the runtime translator
 * (#397) and that module is TypeScript. Invoking it with bare `node` now fails on that import.
 *
 * Resources (src/measure/resources): System + FHIR R4 model-info XML and
 * FHIRHelpers CQL — standard, version-stable config (not a Java dependency).
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  ModelManager,
  LibraryManager,
  CqlTranslator,
  createModelInfoProvider,
  createLibrarySourceProvider,
  createUcumService,
  stringAsSource,
} from "@cqframework/cql/cql-to-elm";
// The SAME validator the runtime translator uses (#397). Build-time and authoring-time must agree:
// a measure that compiles here and fails in the ELM Explorer — or the reverse — is a defect whose cause
// is invisible from either side. Importing a `.ts` module is why this script runs under `--import tsx`.
import { convertUnit, validateUnit } from "../src/measure/ucum.ts";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..");
const resDir = path.join(root, "src/measure/resources");
// Measures are authored as .cql/.yaml text resources (language-agnostic, not Java).
// Source corpus lives in backend-ts/measures/ (relocated from the retired backend/ in #109 PR4).
const measuresDir = process.argv[2] ?? path.join(root, "measures");
const outDir = process.argv[3] ?? path.join(root, "src/engine/cql/elm");
mkdirSync(outDir, { recursive: true });

const systemModelInfoXml = readFileSync(path.join(resDir, "system-modelinfo.xml"), "utf8");
const fhirModelInfoXml = readFileSync(path.join(resDir, "fhir-modelinfo-4.0.1.xml"), "utf8");
const fhirHelpersCql = readFileSync(path.join(resDir, "FHIRHelpers-4.0.1.cql"), "utf8");

// Bundle the translator resources as a static JSON import so the RUNTIME translator
// (src/measure/cql-translator.ts, the live /api/measures/compile path) never reads
// from disk — keeps it portable across every @mieweb/cloud target incl. Cloudflare
// Workers (no node:fs). Regenerated here so a re-vendor of the raw resources stays in sync.
writeFileSync(
  path.join(resDir, "cql-resources.json"),
  JSON.stringify({ systemModelInfoXml, fhirModelInfoXml, fhirHelpersCql }),
);

function manager() {
  const mm = new ModelManager();
  mm.modelInfoLoader.registerModelInfoProvider(
    createModelInfoProvider((name) =>
      name === "System" ? stringAsSource(systemModelInfoXml) : name === "FHIR" ? stringAsSource(fhirModelInfoXml) : null,
    ),
  );
  // Positional: (modelManager, cqlCompilerOptions, libraryCache, lazyUcumService, …). Without the
  // fourth argument the default service THROWS on any quantity literal, so no measure could use a unit.
  const lm = new LibraryManager(mm, undefined, undefined, createUcumService(convertUnit, validateUnit));
  lm.librarySourceLoader.registerProvider(
    createLibrarySourceProvider((name) => (name === "FHIRHelpers" ? stringAsSource(fhirHelpersCql) : null)),
  );
  return lm;
}

function translate(cqlText, label) {
  const json = CqlTranslator.fromText(cqlText, manager()).toJson();
  if (/"errorSeverity"\s*:\s*"error"/i.test(json)) throw new Error(`CQL translation errors in ${label}`);
  return json;
}

const libraries = []; // ELM library names (filename stems) for the generated index
const cqlFiles = readdirSync(measuresDir).filter((f) => f.endsWith(".cql")).sort();
for (const f of cqlFiles) {
  const json = translate(readFileSync(path.join(measuresDir, f), "utf8"), f);
  const id = JSON.parse(json).library.identifier;
  const name = `${id.id}-${id.version}`;
  writeFileSync(path.join(outDir, `${name}.elm.json`), json);
  libraries.push(name);
}
writeFileSync(path.join(outDir, "FHIRHelpers-4.0.1.elm.json"), translate(fhirHelpersCql, "FHIRHelpers-4.0.1"));
libraries.push("FHIRHelpers-4.0.1");

// Generate a static-import index so the engine bundles ELM (no node:fs at runtime —
// portable across every @mieweb/cloud target, incl. Cloudflare Workers).
const imports = libraries.map((n, i) => `import lib${i} from "./${n}.elm.json" with { type: "json" };`).join("\n");
const entries = libraries.map((n, i) => `  ${JSON.stringify(n)}: lib${i},`).join("\n");
writeFileSync(
  path.join(outDir, "index.ts"),
  `// AUTO-GENERATED by scripts/compile-measures.mjs — do not edit.\n${imports}\n\n` +
    `export const ELM_LIBRARIES: Record<string, unknown> = {\n${entries}\n};\n`,
);
console.log(`compiled ${cqlFiles.length} measures + FHIRHelpers (+ index.ts) → ${path.relative(root, outDir)} (pure Node, no JVM)`);
